/**
 * Точка возврата после входа через внешнего провайдера.
 *
 * Значение приходит из запроса на вход и переживает поход к провайдеру,
 * поэтому без проверки увело бы пользователя на чужой сайт сразу после
 * успешного входа. Пропускается только путь внутри приложения: адрес со
 * схемой, а также `//host`, который браузер трактует как внешний адрес,
 * заменяются домашней страницей.
 *
 * Общая для всех протоколов: разошедшиеся копии этой проверки означали бы,
 * что один протокол защищен, а другой нет.
 */
export function safeAppPath(redirect?: string): string {
  if (!redirect) return '/home';
  if (!redirect.startsWith('/') || redirect.startsWith('//')) return '/home';
  return redirect;
}
