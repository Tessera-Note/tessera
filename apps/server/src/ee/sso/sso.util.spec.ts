import { safeAppPath } from './sso.util';

/**
 * Проверка точки возврата общая для всех протоколов входа.
 *
 * Значение переживает поход к провайдеру и возвращается вместе с ним,
 * поэтому непроверенный адрес увел бы пользователя на чужой сайт сразу
 * после успешного входа.
 */
describe('safeAppPath', () => {
  it('путь внутри приложения пропускается', () => {
    expect(safeAppPath('/s/general/p/страница')).toBe('/s/general/p/страница');
  });

  it('пустое значение дает домашнюю страницу', () => {
    expect(safeAppPath(undefined)).toBe('/home');
    expect(safeAppPath('')).toBe('/home');
  });

  it('внешний адрес со схемой отбрасывается', () => {
    expect(safeAppPath('https://зло.example/забрать')).toBe('/home');
  });

  // Браузер трактует //host как внешний адрес, хотя строка начинается с косой.
  it('адрес без схемы отбрасывается', () => {
    expect(safeAppPath('//зло.example/забрать')).toBe('/home');
  });

  it('относительный путь без косой отбрасывается', () => {
    expect(safeAppPath('зло.example')).toBe('/home');
  });
});
