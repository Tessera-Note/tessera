import { languageForRequest } from './request-language.util';

/**
 * Замерено на живом случае: «которые» давало русский ответ, «которіе» с одной
 * украинской буквой давало украинский. Такая зависимость от опечатки
 * непредсказуема, поэтому на смешанном тексте решает локаль.
 */
describe('languageForRequest', () => {
  it('чистый русский запрос дает русский, несмотря на украинскую локаль', () => {
    expect(
      languageForRequest(
        'создай страницу с фильмами которые в прокате',
        'uk-UA',
      ),
    ).toBe('Russian');
  });

  it('чистый украинский запрос дает украинский при русской локали', () => {
    expect(
      languageForRequest('створи сторінку з фільмами у прокаті', 'ru-RU'),
    ).toBe('Ukrainian');
  });

  /**
   * Ровно случай пользователя: русская фраза с одной украинской буквой.
   * Одна такая буква это промах по клавише, а не смена языка, поэтому
   * решают слова, и ответ не зависит от опечатки.
   */
  it.each(['uk-UA', 'ru-RU'])(
    'опечатка в русской фразе языка не меняет, локаль %s',
    (locale) => {
      expect(
        languageForRequest(
          'создай страницу с фильмами которіе в прокате',
          locale,
        ),
      ).toBe('Russian');
    },
  );

  /**
   * Настоящий смешанный текст: признаки обоих языков в силе. Тут решает
   * локаль, потому что выбрать нечем.
   */
  it.each([
    ['uk-UA', 'Ukrainian'],
    ['ru-RU', 'Russian'],
  ])(
    'по-настоящему смешанный текст решается локалью %s',
    (locale, expected) => {
      expect(
        languageForRequest('що це таке и что это такое, если або', locale),
      ).toBe(expected);
    },
  );

  it('кириллица без различающих букв отдает решение локали', () => {
    expect(languageForRequest('привет как дела', 'uk-UA')).toBe('Ukrainian');
    expect(languageForRequest('привет как дела', 'ru-RU')).toBe('Russian');
  });

  it('текст без кириллицы решается локалью', () => {
    expect(languageForRequest('create a page with films', 'ru-RU')).toBe(
      'Russian',
    );
  });

  it('пустое сообщение решается локалью', () => {
    expect(languageForRequest('', 'de-DE')).toBe('German');
  });

  it('без локали язык по умолчанию', () => {
    expect(languageForRequest('hello', null)).toBe('English');
  });
});

/**
 * У разговора есть язык. Короткая реплика без признаков наследует его, а не
 * падает на локаль интерфейса.
 *
 * Замерено на живом случае: «а можешь их все перенести в 1 папку» не содержит
 * ни одного слова из списков, и при украинской локали ответ приходил
 * украинским посреди русского разговора.
 */
describe('languageForRequest, язык разговора', () => {
  const SHORT = 'а можешь их все перенести в 1 папку';
  const RUSSIAN_EARLIER =
    'поудаляй все страницы кроме 8 триллеров со сложным и логически выверенным сюжетом';

  it('без разговора короткая реплика падает на локаль', () => {
    expect(languageForRequest(SHORT, 'uk-UA')).toBe('Ukrainian');
  });

  it('с русским разговором короткая реплика остается русской', () => {
    expect(languageForRequest(SHORT, 'uk-UA', [RUSSIAN_EARLIER])).toBe(
      'Russian',
    );
  });

  /** Явные признаки самой реплики сильнее разговора: человек мог перейти. */
  it('признаки нынешней реплики сильнее разговора', () => {
    expect(
      languageForRequest('створи сторінку', 'ru-RU', [RUSSIAN_EARLIER]),
    ).toBe('Ukrainian');
  });

  it('берется ближайшая реплика с признаками', () => {
    expect(
      languageForRequest(SHORT, 'ru-RU', [RUSSIAN_EARLIER, 'створи сторінку']),
    ).toBe('Ukrainian');
  });

  it('молчащий разговор отдает решение локали', () => {
    expect(languageForRequest(SHORT, 'uk-UA', ['ок', '123'])).toBe('Ukrainian');
  });

  /**
   * «та», «до» и «у» употребляются и в русском, поэтому как признак
   * украинского они были ложными.
   */
  it('общие для двух языков слова украинского не дают', () => {
    expect(languageForRequest('дойди до конца у него', 'ru-RU')).toBe(
      'Russian',
    );
  });
});
