import { languageFromLocale } from './ai-language.util';

/**
 * На каком языке отвечать на это сообщение.
 *
 * Язык ответа следует языку просьбы, а не локали интерфейса: страница,
 * созданная по русскому запросу, должна быть русской, даже если интерфейс
 * украинский. Но решение принимает сервер, а не модель.
 *
 * Причина: на смешанном тексте модель угадывает по-разному от раза к разу.
 * Замерено на живом случае — «которые» давало русский ответ, «которіе» с
 * одной украинской буквой давало украинский. Такая зависимость от опечатки
 * непредсказуема для человека.
 *
 * Различаются два близких языка, поэтому одних букв мало: во фразе «создай
 * страницу с фильмами которые в прокате» нет ни одной буквы, которой не было
 * бы в украинском. Решают служебные слова, у которых в этих языках разные
 * формы, а буквы работают только как дополнительный признак и только при
 * повторении: одна украинская буква посреди русской фразы это опечатка, а не
 * язык.
 *
 * Ничья, отсутствие признаков и смешанный текст отдают решение локали.
 */

