/** Буквы, которых нет в русском алфавите. */
const UKRAINIAN_LETTERS = /[єіїґ]/gi;

/** Буквы, которых нет в украинском алфавите. */
const RUSSIAN_LETTERS = /[ыъэё]/gi;

/**
 * Сколько исключительных букв делает признак языком, а не опечаткой.
 *
 * Одна такая буква посреди фразы другого языка это промах по клавише, что и
 * наблюдалось: «которіе» вместо «которые».
 */
const MIN_LETTERS = 2;

/** Кириллица вообще: без нее спорить не о чем. */
const CYRILLIC = /[Ѐ-ӿ]/;

function count(text: string, pattern: RegExp): number {
  return (text.match(pattern) ?? []).length;
}

export function languageForRequest(
  message: string,
  locale: string | null | undefined,
): string {
  const fallback = languageFromLocale(locale);

  if (!message || !CYRILLIC.test(message)) return fallback;

  const words = message
    .toLowerCase()
    .replace(/[^\p{L}\s]+/gu, ' ')
    .split(/\s+/)
    .filter(Boolean);

  let russian = words.filter((word) => RUSSIAN_WORDS.has(word)).length;
  let ukrainian = words.filter((word) => UKRAINIAN_WORDS.has(word)).length;

  if (count(message, RUSSIAN_LETTERS) >= MIN_LETTERS) russian += 1;
  if (count(message, UKRAINIAN_LETTERS) >= MIN_LETTERS) ukrainian += 1;

  if (russian === ukrainian) return fallback;

  return russian > ukrainian ? 'Russian' : 'Ukrainian';
}
