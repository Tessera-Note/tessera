/**
 * Нужен ли запросу внешний поиск.
 *
 * У агента нет настоящего вызова инструментов (см. `docs/future-roadmap.md`),
 * поэтому решить, что нужны свежие данные, модель не может — решает сервер.
 *
 * Решение принимается по **характеру запроса**, а не по факту пустой выдачи
 * из вики: запрос про текущие события нередко даёт совпадение по словам и всё
 * равно требует свежих данных.
 *
 * Из трёх способов выбран этот. Отдельный вызов модели «нужен ли поиск»
 * удваивает задержку и ломает обычный чат при недоступном провайдере. Искать
 * всегда неприемлемо для закрытого контура. Признаки в тексте дёшевы,
 * предсказуемы и объяснимы администратору.
 *
 * Названная цена: запрос без маркеров, которому свежесть всё же нужна, поиск
 * не запустит. Смягчается тем, что явная просьба поискать срабатывает всегда.
 * При появлении настоящего tool-calling это решение выбрасывается целиком.
 */
const EXPLICIT = [
  'поищи', 'найди в интернете', 'погугли', 'поиск в интернете', 'в сети',
  'search the web', 'google it', 'look it up', 'search online',
];

const FRESHNESS = [
  // русский
  'сейчас', 'сегодня', 'вчера', 'завтра', 'текущий', 'текущая', 'текущее',
  'текущие', 'последние', 'свежие', 'новости', 'новинки', 'вышел', 'вышла',
  'вышли', 'выходит', 'прокат', 'афиша', 'расписание', 'курс', 'погода',
  'в этом году', 'в этом месяце', 'на этой неделе', 'актуальн',
  // английский
  'today', 'yesterday', 'tomorrow', 'current', 'currently', 'latest', 'recent',
  'news', 'now playing', 'box office', 'this year', 'this month', 'this week',
  'weather', 'exchange rate', 'released', 'upcoming',
];

/** Год в разумном диапазоне: 2000-2099. */
const YEAR = /\b20\d{2}\b/;

export function needsWebSearch(query: string): boolean {
  if (!query) return false;

  const text = query.toLowerCase();

  if (EXPLICIT.some((marker) => text.includes(marker))) return true;
  if (FRESHNESS.some((marker) => text.includes(marker))) return true;

  return YEAR.test(text);
}
