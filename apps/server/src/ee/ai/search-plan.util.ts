import { buildWebSearchQuery } from './search-query.util';

/**
 * Несколько поисковых заходов вместо одного.
 *
 * Замерено на живом случае: на просьбу собрать топ-13 проката ушёл ровно один
 * запрос, вернулось пять ссылок, агент взял из них обрывок и опубликовал
 * страницу с местами с девятого по тринадцатое. Одна выдача одного
 * формулирования — это не «поискал», это «спросил один раз и согласился с
 * первым, что дали».
 *
 * Настоящего вызова инструментов у агента нет, поэтому уточнять запрос
 * приходится серверу. Модель об этом не спрашивают по тем же причинам, что и
 * про необходимость поиска: лишний вызов удваивает задержку и ломает чат при
 * недоступном провайдере.
 *
 * Заходы строятся из самого запроса и различаются тем, что в них добавлено:
 *
 * 1. ядро запроса, как есть;
 * 2. ядро с текущим годом — отсекает статьи прошлых лет, которых в выдаче по
 *    «текущему» всегда много;
 * 3. короткое ядро из первых значимых слов — длинный запрос сужает выдачу,
 *    короткий достаёт списки и обзоры, которых длинный не находит;
 * 4. ядро со словом-подсказкой вида «список» или «рейтинг», когда человек
 *    просит перечисление.
 *
 * Заходы выполняются все: свой сервис поиска стоит рядом в compose, чужого
 * счёта эти запросы не увеличивают. Результаты объединяются по адресу.
 */

/** Сколько слов остаётся в укороченном заходе. */
const SHORT_WORDS = 4;

/** Просьба перечислить: тогда полезен заход со словом-подсказкой. */
const LIST_MARKERS = [
  'топ',
  'список',
  'перечисли',
  'рейтинг',
  'подборка',
  'top',
  'list',
  'ranking',
];

/** Год в запросе уже есть: добавлять второй незачем. */
const YEAR = /\b20\d{2}\b/;

export function buildSearchPlan(message: string, year: number): string[] {
  const core = buildWebSearchQuery(message);
  if (!core) return [];

  const plan: string[] = [core];
  const words = core.split(' ').filter(Boolean);

  if (!YEAR.test(core)) {
    plan.push(`${core} ${year}`);
  }

  if (words.length > SHORT_WORDS) {
    const short = words.slice(0, SHORT_WORDS).join(' ');
    plan.push(YEAR.test(short) ? short : `${short} ${year}`);
  }

  const asksForList = LIST_MARKERS.some((marker) => core.includes(marker));
  if (asksForList) {
    const short = words.slice(0, SHORT_WORDS).join(' ');
    plan.push(`${short} рейтинг ${year}`);
  }

  // Один и тот же запрос дважды выдачу не расширяет.
  return [...new Set(plan)];
}
