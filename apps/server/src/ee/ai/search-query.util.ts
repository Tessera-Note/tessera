  'добавь',
  'добавить',
  'обнови',
  'обновить',
  'подготовь',
  'оформи',
  'оформить',
  'сформируй',
  'заполни',
  'страницу',
  'страница',
  'страницы',
  'сторінку',
  'список',
  'списком',
  'таблицу',
  'таблица',
  'заметку',
  'документ',
  'мне',
  'пожалуйста',
  // английский
  'create',
  'make',
  'write',
  'add',
  'update',
  'prepare',
  'draft',
  'compile',
  'page',
  'list',
  'table',
  'note',
