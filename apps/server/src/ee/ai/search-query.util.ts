/** Сколько слов уходит в поиск: длинный запрос сужает выдачу до нуля. */
const MAX_WORDS = 12;

/** Ниже этого порога очистка съела слишком много, и запрос теряет смысл. */
const MIN_WORDS = 2;

export function buildWebSearchQuery(message: string): string {
  if (!message) return '';

  const original = message.trim();

  const words = original
    .toLowerCase()
    // Знаки препинания разделяют слова, дефис внутри слова сохраняется.
    .replace(/[^\p{L}\p{N}\-]+/gu, ' ')
    .split(' ')
    .filter(Boolean);

  const kept: string[] = [];
  const seen = new Set<string>();

  for (const word of words) {
    if (COMMAND_WORDS.has(word) || STOP_WORDS.has(word)) continue;
    // Повтор ничего не уточняет: «топ 12 ... 12» это те же 12.
    if (seen.has(word)) continue;

    seen.add(word);
    kept.push(word);

    if (kept.length === MAX_WORDS) break;
  }

  // Сообщение, состоящее почти целиком из обращения к агенту, лучше искать
  // как есть, чем по одному оставшемуся слову.
  if (kept.length < MIN_WORDS) return original;

  return kept.join(' ');
}
