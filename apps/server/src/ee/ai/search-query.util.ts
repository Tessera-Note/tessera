/**
 * Поисковый запрос из сообщения человека.
 *
 * В поиск уходил текст сообщения целиком, вместе с обращением к агенту.
 * Замерено на живом стенде: «создай страницу с текущими 12 фильмами которіе
 * в прокате в топ 12» дало Reddit про приложения для списков, промокоды
 * онлайн-кинотеатра и главу «Золотого телёнка», после чего агент честно
 * ответил, что проверяемых данных нет. Тот же запрос без слов-команд и
 * служебных слов дает «Список лидеров кинопроката 2026» первой строкой.
 *
 * Отбрасываются два класса слов. Первый — обращение к самому агенту:
 * «создай», «страницу», «список». Они относятся к тому, что сделать с
 * результатом, а не к тому, что искать, и уводят поиск в сторону сильнее
 * всего. Второй — служебные слова, которые ничего не добавляют к запросу.
 *
 * Извлечение по спискам слов, а не отдельным вызовом модели, по тем же
 * причинам, что и у `needsWebSearch`: вызов удваивает задержку и ломает чат
 * при недоступном провайдере, а списки дешевы, предсказуемы и объяснимы.
 */

/** Обращение к агенту: что сделать с результатом, а не что искать. */
