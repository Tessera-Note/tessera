/**
 * Как часто перепроверяются права у уже открытых соединений.
 *
 * `onAuthenticate` отрабатывает один раз, на подключении. Без обхода человек,
 * которого убрали из группы или отключили, продолжал бы читать и править
 * открытый документ до тех пор, пока сам не закроет вкладку.
 *
 * Тридцать секунд это тот же порядок, что у собственного `timeout` Hocuspocus:
 * окно доступа ограничено, а нагрузка на базу остается пренебрежимой, потому
 * что проверка идет один раз на человека в документе, а не на соединение.
 */
export const ACCESS_SWEEP_INTERVAL_MS = 30 * 1000;

/**
 * Служебные сообщения канала коллаборации.
 *
 * Клиент разбирает их в `onStateless` и игнорирует незнакомые типы, поэтому
 * старая версия клиента новый тип просто не заметит.
 */
export const COLLAB_ACCESS_REVOKED = 'access.revoked';
export const COLLAB_ACCESS_CHANGED = 'access.changed';
