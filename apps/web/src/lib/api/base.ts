import { browser } from '$app/environment';
import { PUBLIC_API_URL } from '$env/static/public';

/**
 * Куда обращаться. Адреса два, и это не дублирование.
 *
 * Браузер ходит на тот же источник, что и страница: обратный прокси отдаёт и
 * страницу, и `/api`. Сервер так ходить не может: пустой адрес означает для
 * него запрос к самому себе, а на `/api` он не отвечает и заводит запрос
 * заново — рекурсия до исчерпания памяти. Найдено падением: процесс принимал
 * первый запрос и умирал, съев четыре гигабайта.
 *
 * Адрес для отрисовки на сервере ставится один раз при запуске
 * (`hooks.server.ts`): читать его здесь нельзя, этот файл общий с браузером, а
 * приватное окружение туда попадать не должно.
 */
let serverBase = '';

export function setServerApiBase(value: string): void {
  serverBase = value.replace(/\/+$/, '');
}

export function apiBase(): string {
  return browser ? (PUBLIC_API_URL || '').replace(/\/+$/, '') : serverBase;
}
