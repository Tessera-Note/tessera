/**
 * Признак листа печати.
 *
 * Узел, который на экране рисуется окном чужого сайта, в печати не загружается
 * — ни на закрытом контуре, ни через список разрешённых адресов Gotenberg, — и
 * на листе остаётся пустой прямоугольник. Признак ставит отрисовщик листа
 * (`routes/(render)/pdf-render`), а узлы по нему рисуют то, что можно прочесть
 * на бумаге: название и адрес ссылкой.
 *
 * Признаком, а не медиавыражением `@media print`: печать идёт не браузером
 * человека, а Gotenberg по адресу листа, и вид носителя ему не задаётся
 * (`services/pdf_export.py`). Полагаться на `print` означало бы замерять это
 * заново при каждом обновлении образа Gotenberg.
 */
class PrintSheet {
  /** Рисуется ли сейчас лист печати, а не экран. */
  active = $state(false);
}

export const printSheet = new PrintSheet();
