/**
 * Безопасный отрывок с подсветкой.
 *
 * Отрывок приходит от `ts_headline`, а он строится из содержимого страницы —
 * то есть из того, что пишет человек. Вставлять его разметкой как есть нельзя:
 * это внедрение чужой разметки в страницу поиска.
 *
 * В v1 отрывок пропускают через очиститель, разрешая единственный тег. Здесь
 * то же самое, но без зависимости: всё экранируется, а затем возвращается
 * ровно та пара тегов, которой сервер обрамляет совпадение. Разрешительный
 * подход, а не запретительный: список запретов всегда неполон.
 */

const BOLD_OPEN = '&lt;b&gt;';
const BOLD_CLOSE = '&lt;/b&gt;';

export function highlightHtml(raw: string | null | undefined): string {
  if (!raw) return '';
  const escaped = raw
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;');
  return escaped.replaceAll(BOLD_OPEN, '<b>').replaceAll(BOLD_CLOSE, '</b>');
}
