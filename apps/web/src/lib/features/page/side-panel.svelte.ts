/**
 * Открыта ли правая панель страницы.
 *
 * В v1 панель открывается кнопкой и закрывается крестиком, а по умолчанию
 * закрыта: страница читается во всю ширину. Здесь она была открыта всегда и
 * забирала у текста триста пятьдесят точек — на узком экране от содержимого
 * оставалась колонка в половину.
 *
 * Выбор запоминается в браузере: это удобство одного человека на одном
 * устройстве, и место ему в хранилище браузера, а не в учётной записи.
 */

const STORAGE_KEY = 'tessera.page-aside';

class SidePanelStore {
  open = $state(false);

  /** Прочитать выбранное. Вызывается на клиенте: в разметке сервера окна нет. */
  hydrate() {
    try {
      this.open = localStorage.getItem(STORAGE_KEY) === 'open';
    } catch {
      // Хранилище недоступно в закрытом окне. Панель останется закрытой.
    }
  }

  toggle() {
    this.open = !this.open;
    try {
      localStorage.setItem(STORAGE_KEY, this.open ? 'open' : 'closed');
    } catch {
      // То же: выбор проживёт до перезагрузки.
    }
  }
}

export const sidePanel = new SidePanelStore();
