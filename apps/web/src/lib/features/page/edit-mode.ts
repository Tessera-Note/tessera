/**
 * С чего открывается страница: с чтения или сразу с правки.
 *
 * Правило простое — предпочтение человека из настроек, по умолчанию чтение,
 * как в v1: случайная правка чужой страницы хуже лишнего нажатия. Сложность в
 * том, **когда** это правило применяется.
 *
 * Экран переносит `data` в своё состояние эффектом, а эффект выполняется на
 * каждом ответе сервера, не только на первом. Перечитывает же данные почти
 * всякое действие на странице: подписка, переименование, метка, комментарий,
 * событие от соседа. Безусловное присваивание выбрасывало бы человека из
 * правки посреди набора. Поэтому режим ставится один раз на страницу, а
 * дальше переключателем распоряжается только человек.
 */

export type EditModeGate = {
  /**
   * Каким сделать переключатель для этой страницы.
   *
   * `null` означает «не трогать»: для этой страницы режим уже поставлен.
   */
  decide(pageId: string, canEdit: boolean, preference: string | null | undefined): boolean | null;
};

export function editModeGate(): EditModeGate {
  let appliedFor: string | null = null;

  return {
    decide(pageId, canEdit, preference) {
      if (appliedFor === pageId) return null;
      appliedFor = pageId;
      return canEdit && preference === 'edit';
    }
  };
}
