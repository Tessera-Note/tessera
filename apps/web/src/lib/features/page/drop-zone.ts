/**
 * Место броска при перетаскивании страниц в дереве.
 *
 * Отдельно от состояния перетаскивания (`drag.svelte.ts`): там руны, а они
 * живут только внутри сборки Svelte, и проверка не прочитала бы файл целиком.
 */

/** Куда встанет страница относительно строки, над которой держат указатель. */
export type DropZone = 'before' | 'inside' | 'after';

/** Доля высоты строки сверху и снизу, отведённая под «до» и «после». */
const EDGE = 0.3;

/**
 * Место броска по положению указателя внутри строки.
 *
 * Три полосы: верхняя треть ставит страницу перед строкой, нижняя — после,
 * середина делает её вложенной. Так же ведут себя деревья в проводниках, и
 * иного способа выразить вложение одним движением нет.
 */
export function zoneAt(offsetY: number, height: number): DropZone {
  if (height <= 0) return 'inside';
  const share = offsetY / height;
  if (share < EDGE) return 'before';
  if (share > 1 - EDGE) return 'after';
  return 'inside';
}
