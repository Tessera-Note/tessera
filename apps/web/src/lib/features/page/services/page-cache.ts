/**
 * Однократный запрос страницы на показ.
 *
 * Нужен упоминаниям: одна и та же страница упоминается в тексте по нескольку
 * раз, и запрос на каждое упоминание означал бы десяток одинаковых обращений
 * при каждом открытии. Кеш держит и отказ: закрытая правами страница иначе
 * спрашивалась бы заново каждым своим упоминанием.
 *
 * Отдельно от `pages.ts`: там обращения к серверу, здесь — учёт уже
 * спрошенного. Смешение этих двух вещей означало бы кеш у правки и удаления,
 * то есть выдачу устаревшего там, где нужен свежий ответ.
 */

import { pageInfo, type PageBody } from './pages';

/** Срок годности. Заголовок меняется редко, а показ переспрашивает при
 *  повторном открытии страницы. Тот же срок, что у подписей упоминаний. */
const FRESH_MS = 5 * 60 * 1000;

type Held = { at: number; answer: Promise<PageBody> };

const held = new Map<string, Held>();

/**
 * Страница по её ключу, не более одного запроса на срок годности.
 *
 * Отказ отдаётся всем, кто ждал: различать 404 и 403 — дело вызывающего.
 */
export function pageOnce(pageId: string): Promise<PageBody> {
  const known = held.get(pageId);
  if (known && Date.now() - known.at < FRESH_MS) {
    return known.answer;
  }
  const answer = pageInfo(pageId);
  held.set(pageId, { at: Date.now(), answer });
  // Отказ не должен всплывать необработанным, если ждать его будут позже:
  // браузер сообщил бы о нём в журнал как о недосмотре.
  answer.catch(() => {});
  return answer;
}
