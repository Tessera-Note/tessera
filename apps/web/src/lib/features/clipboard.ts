/**
 * Копирование в буфер обмена.
 *
 * Заведено после находки ревью: в четырёх местах копирование было записано как
 * `navigator.clipboard?.writeText(...)` — без ожидания, без разбора отказа и
 * без признака «скопировано». В незащищённом соединении (развёртывание по
 * `http://`) свойства `clipboard` у браузера нет вовсе, знак `?.` тихо гасит
 * вызов, и человек уходит с уверенностью, что ссылка у него в буфере.
 *
 * Здесь отказ виден вызывающему, и он решает, что показать.
 */

/** Скопировать. Отвечает, получилось ли. */
export async function copyText(text: string): Promise<boolean> {
  try {
    // Свойства может не быть: обращение через `?.` дало бы `undefined`, а не
    // отказ, и `await` над ним прошёл бы успешно.
    if (!navigator.clipboard) return false;
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    // Браузер не дал права. Отличать это от отсутствия буфера вызывающему
    // незачем: показать он может только одно — «не получилось».
    return false;
  }
}
