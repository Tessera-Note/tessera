/**
 * Ширина листа на странице по ссылке.
 *
 * У постороннего читателя настроек нет: он не входит и до «Настроек чтения» не
 * доберётся. В v1 переключатель ширины стоит прямо в шапке такой страницы, и
 * это единственное место, где читатель может расширить лист под таблицу или
 * сузить под текст.
 *
 * Выбор помнится в браузере читателя: он относится к тому, как человек читает,
 * и переносить его на сервер незачем — учётной записи у него нет.
 */

const STORAGE_KEY = 'tessera.share.wide';

class ShareWidth {
  /** Во всю ширину. Умолчание — узкий лист, как у страницы внутри вики. */
  wide = $state(false);

  /** Прочитать выбранное. Вызывается на клиенте: в разметке сервера окна нет. */
  hydrate(): void {
    if (typeof window === 'undefined') return;
    try {
      this.wide = localStorage.getItem(STORAGE_KEY) === 'true';
    } catch {
      // Хранилище недоступно в закрытом окне. Останется умолчание.
    }
  }

  toggle(): void {
    this.wide = !this.wide;
    try {
      localStorage.setItem(STORAGE_KEY, String(this.wide));
    } catch {
      // Не сохранилось — выбор действует до закрытия вкладки.
    }
  }
}

export const shareWidth = new ShareWidth();
