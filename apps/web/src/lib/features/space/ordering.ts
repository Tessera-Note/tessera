/**
 * Порядок пространств в боковой панели.
 *
 * Отмеченные идут первыми. В v1 под них отведён отдельный раздел панели, потому
 * что остальных пространств там нет вовсе; здесь панель показывает все, и второй
 * раздел повторял бы половину списка.
 *
 * Внутри групп порядок сервера сохраняется: сравнение смотрит только на отметку,
 * а сортировка устойчива. Иначе перечень переставлялся бы на каждом открытии по
 * правилу, которого человек не задавал.
 */

/** Пространство в объёме, нужном порядку. */
export type Ordered = { id: string };

export function favoritesFirst<T extends Ordered>(
  spaces: readonly T[],
  favorites: ReadonlySet<string>
): T[] {
  return [...spaces].sort((a, b) => Number(favorites.has(b.id)) - Number(favorites.has(a.id)));
}
