/**
 * Какое пространство открыто сейчас.
 *
 * Обычно оно стоит прямо в адресе: `/s/<пространство>/...`. У базы адрес свой —
 * `/base/<идентификатор>`, — потому что экран базы один на все пространства, и
 * пространства в нём нет. Тогда оно берётся из данных экрана: боковая панель
 * раскрывает дерево только у открытого пространства, и без второго источника
 * дерево пропадало, стоило открыть базу — а попадают в неё как раз из дерева.
 */

/**
 * Данные экрана в объёме, нужном правилу.
 *
 * Читается одно поле, и у большинства экранов его нет вовсе: тип принимает
 * любые данные и сам разбирается, есть ли в них пространство.
 */
export type WithSpace = Record<string, unknown> | null | undefined;

export function openSpaceSlug(
  params: Record<string, string | undefined>,
  data: WithSpace
): string | null {
  const space = data?.space as { slug?: string } | null | undefined;
  return params.spaceSlug ?? space?.slug ?? null;
}
