/**
 * Чего не хватает `jsdom` до браузера.
 *
 * `jsdom` разбирает разметку и хранит дерево, но не раскладывает его: у него
 * нет ни размеров, ни прокрутки. Компоненты, которые держат выбранную строку в
 * виду или измеряют строку перед показом меню, зовут эти методы, и без заглушек
 * проверка падает на устройстве среды, а не на поведении.
 *
 * Заглушки ничего не изображают. Прокрутка проверяется глазами в браузере, а
 * здесь важно лишь то, что вызов не роняет отрисовку.
 */

if (!Element.prototype.scrollIntoView) {
  Element.prototype.scrollIntoView = function scrollIntoView(): void {};
}

/**
 * События указателя. В `jsdom` класса `PointerEvent` нет вовсе, а компоненты
 * слушают `pointerdown`: он приходит и от мыши, и от пальца, и от пера, тогда
 * как `mousedown` от пальца приходит с задержкой. Замена мышиным событием
 * достаточна: обработчики читают из него только цель и координаты.
 */
if (typeof globalThis.PointerEvent === 'undefined') {
  globalThis.PointerEvent = MouseEvent as unknown as typeof PointerEvent;
}
