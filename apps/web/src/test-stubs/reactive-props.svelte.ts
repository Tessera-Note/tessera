/**
 * Изменяемые свойства для проверок разметки.
 *
 * `mount` принимает обычный объект, и запись в него до компонента не доходит:
 * чтобы проверить, как компонент отвечает на смену свойства, нужен объект под
 * рунами. Руны работают только в файлах с `.svelte.ts`, поэтому эта мелочь
 * живёт отдельным модулем, а не внутри самой проверки.
 *
 * Заведено после негодной проверки: она пересоздавала компонент вместо смены
 * свойства и поэтому проходила и без исправления.
 */

/** Объект свойств, чью правку компонент видит. */
export function reactiveProps<T extends object>(initial: T): T {
  // Присваивание переменной, а не возврат выражения: руну разрешено ставить
  // только объявлением, и `return $state(...)` компилятор не принимает.
  const props = $state(initial);
  return props;
}
