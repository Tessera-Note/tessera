/**
 * Означает ли ошибка загрузки чата, что чат человеку недоступен.
 *
 * Раньше из чата выбрасывало на любую ошибку запроса сведений о нем. Отказ по
 * частоте запросов возвращает 429, и человек терял открытый разговор из-за
 * временного ограничения, не понимая причины: адрес чата просто менялся на
 * список. То же самое давали любая ошибка сервера и обрыв сети.
 *
 * Уводить с адреса нужно только тогда, когда чат действительно чужой или его
 * нет: остальное проходит само и лечится повтором.
 */
export function isChatAccessError(error: unknown): boolean {
  const status = (error as { response?: { status?: number } })?.response
    ?.status;

  return status === 403 || status === 404;
}
