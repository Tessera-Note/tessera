#!/usr/bin/env bash
# Блокирует Edit/Write/MultiEdit к путям, которые в этом репозитории
# никогда не правятся руками.
# Зависимости: bash, jq.
#
# Существующие миграции здесь намеренно не блокируются: штатный поток
# migration:create создает файл-заготовку, которую затем надо наполнить.
# Правило "существующие миграции не редактируются" держится на CLAUDE.md
# и на агенте schema-reviewer, а не на этом хуке.
#
# Словари локалей кроме en-US тоже не блокируются, но они управляются
# Crowdin и ручная правка будет перетерта при следующей синхронизации.
# См. .claude/skills/i18n/SKILL.md.

set -euo pipefail

input=$(cat)
file=$(echo "$input" | jq -r '.tool_input.file_path // .tool_input.path // ""')

if [ -z "$file" ]; then
  exit 0
fi

rel="${file#"$(pwd)/"}"

# Каждый элемент это пара "регулярка##причина".
# Разделитель именно ##, потому что | встречается внутри самих регулярок.
# Кавычки одинарные: в двойных bash раскрыл бы $## как переменную $# и
# сломал бы правила с якорем конца строки.
deny_rules=(
  '(^|/)node_modules/##устанавливается пакетным менеджером'
  '^\.nx/##кеш Nx'
  '^apps/[^/]+/dist/##артефакт сборки'
  '^packages/[^/]+/dist/##артефакт сборки'
  '^\.env$##секреты, запись запрещена, чтение для диагностики разрешено'
  '^\.env\.##секреты, запись запрещена'
  '^pnpm-lock\.yaml$##регенерируется через pnpm install'
  '^patches/##генерируется через pnpm patch'
  '^apps/server/src/database/types/db\.d\.ts$##генерируется через pnpm --filter server migration:codegen'
  '^__temp__/##каталог референсов, не часть проекта'
)

for rule in "${deny_rules[@]}"; do
  pat="${rule%%##*}"
  reason="${rule#*##}"
  if echo "$rel" | grep -Eq "$pat"; then
    echo "BLOCKED: правка '$rel' запрещена политикой проекта" 1>&2
    echo "Причина: $reason" 1>&2
    exit 2
  fi
done

exit 0
