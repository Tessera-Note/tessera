async def seed_initial_content(session: AsyncSession) -> None:
    """Наполнить базу страницами и первым выпуском."""
    doc_repo = DocPageRepo(session)
    for page in DOC_PAGES:
        await doc_repo.upsert(
            slug=str(page["slug"]),
            section=str(page["section"]),
            title=str(page["title"]),
            body=str(page["body"]),
            position=int(page["position"]),  # type: ignore[arg-type]
        )

    version = os.environ.get("HUB_SEED_RELEASE_VERSION", "").strip()
    if not version:
        return

    release_repo = ReleaseRepo(session)
    if await release_repo.get_by_version(version) is not None:
        return
    await release_repo.add(
        version=version,
        notes="Первичная регистрация версии экземпляра.",
        is_latest=await release_repo.latest() is None,
    )
